export function PixelSprite({
  name,
  glyph,
  size = 22,
  className = "",
}: {
  name?: string;
  glyph?: string[];
  size?: number;
  className?: string;
}) {
  const rows = glyph ?? GLYPHS[name ?? "agents"] ?? GLYPHS.agents;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 8 8"
      className={className}
      shapeRendering="crispEdges"
      aria-hidden
    >
      {rows.map((row, y) =>
        row.split("").map((c, x) =>
          c === "#" ? (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill="currentColor" />
          ) : null
        )
      )}
    </svg>
  );
}

/** Convenience wrapper for role avatars, e.g. <AgentSprite role="RESEARCH" />. */
export function AgentSprite({
  role,
  size = 20,
  className = "",
}: {
  role: string;
  size?: number;
  className?: string;
}) {
  return <PixelSprite name={role.toUpperCase()} size={size} className={className} />;
}
